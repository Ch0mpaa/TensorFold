#!/usr/bin/env python3
"""Emit or verify the bounded QNN fixture from the checked-in EXL3 oracle.

This intentionally consumes the fixture's FP64 dequantization oracle rather than
reimplementing EXL3: the fixture is the checked-in, independently tested decoder
oracle for its one public 128x128 block.  No model download or vendor SDK is used.
"""
from __future__ import annotations

import argparse
import hashlib
import math
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "zig/tests/fixtures/exl3_oracle.bin"
OUTPUT = ROOT / "app/mobile/modules/tensorfold-local-runtime/native/qnn_full_projection.h"
FIXTURE_SHA256 = "8eecb6ac56325a50634eaf75cd2c2ff4aed74e4341b5f2af6c05a3bf0985c810"
MODEL_SHA256 = "a106b1c9d58a768eb87960daa7aff6efd250b0cb7c73edb92155ac9fc653f45f"


def u16(data: bytes, at: int) -> int:
    return struct.unpack_from("<H", data, at)[0]


def u32(data: bytes, at: int) -> int:
    return struct.unpack_from("<I", data, at)[0]


def u64(data: bytes, at: int) -> int:
    return struct.unpack_from("<Q", data, at)[0]


def records_end(data: bytes) -> int:
    if data[:8] != b"EXL3ORAC":
        raise ValueError("fixture magic is not EXL3ORAC")
    at = 16
    for _ in range(u64(data, 8)):
        halves, kt, nt = u16(data, at), u32(data, at + 4), u32(data, at + 8)
        if halves == 0:
            raise ValueError("invalid fixture record width")
        # Width.tileWords() is 8 * halves (one i16 word per packed state).
        at += 12 + kt * nt * (8 * halves * 2 + 256 * 4)
    return at


def oracle_block(data: bytes) -> tuple[tuple[int, int, int], list[float]]:
    at = records_end(data)
    spots = u32(data, at)
    at += 4 + spots * 6
    halves, kt, nt, trellis_len = u16(data, at), u32(data, at + 2), u32(data, at + 6), u32(data, at + 10)
    at += 14 + trellis_len
    suh_len = u32(data, at)
    at += 4 + suh_len
    svh_len = u32(data, at)
    at += 4 + svh_len
    wq_len = u32(data, at)
    at += 4 + wq_len
    dq_len = u32(data, at)
    at += 4
    if (halves, kt, nt) != (16, 8, 8) or dq_len != 128 * 128 * 8 or at + dq_len != len(data):
        raise ValueError("fixture does not contain the expected complete 128x128 mcg block")
    return (halves, kt, nt), list(struct.unpack_from("<16384d", data, at))


def quantize_symmetric(values: list[float], scale: float) -> list[int]:
    # Exact ties are resolved away from zero, independent of Python's round mode.
    result = []
    for value in values:
        q = math.floor(abs(value) / scale + 0.5)
        q = q if value >= 0 else -q
        if not -127 <= q <= 127:
            raise ValueError("quantization range unexpectedly saturated")
        result.append(q + 128)
    return result


def format_array(values: list[int], width: int = 16) -> str:
    return "\n".join("    " + ", ".join(str(v) for v in values[i:i + width]) + "," for i in range(0, len(values), width))


def format_float_array(values: list[float], width: int = 4) -> str:
    return "\n".join("    " + ", ".join(f"{v:.8e}f" for v in values[i:i + width]) + "," for i in range(0, len(values), width))


def payload_sha(input_u8: list[int], weights_u8: list[int], dots: list[int], scales: tuple[float, float, float]) -> str:
    packed = bytes(input_u8) + bytes(weights_u8)
    packed += struct.pack("<128i", *dots)
    packed += struct.pack("<3d", *scales)
    return hashlib.sha256(packed).hexdigest()


def render(data: bytes) -> str:
    (halves, kt, nt), weights = oracle_block(data)
    # A fixed bounded activation, selected deterministically rather than sampled
    # from a private prompt or model activation.
    input_signed = [((index * 73 + 19) % 255) - 127 for index in range(128)]
    input_u8 = [value + 128 for value in input_signed]
    input_scale = 1.0 / 127.0
    weight_scale = max(abs(value) for value in weights) / 127.0
    weights_u8 = quantize_symmetric(weights, weight_scale)
    weight_signed = [value - 128 for value in weights_u8]
    dots = [sum(input_signed[k] * weight_signed[k * 128 + n] for k in range(128)) for n in range(128)]
    references = [dot * input_scale * weight_scale for dot in dots]
    # 100 codes leave at least 27 codes of headroom on either side.
    output_scale = max(abs(value) for value in references) / 100.0
    if output_scale == 0.0:
        raise ValueError("degenerate full-block projection")
    output_offset = -128
    rounded = [math.floor(value / output_scale + 0.5) for value in references]
    if any(not -127 <= value <= 127 for value in rounded):
        raise ValueError("output scale would saturate")
    digest = payload_sha(input_u8, weights_u8, dots, (input_scale, weight_scale, output_scale))
    return f'''#pragma once

#include <cstdint>

namespace tensorfold::qnn_full_projection {{

// Generated by tools/generate_qnn_full_projection.py from checked-in bytes.
// Verify with: python tools/generate_qnn_full_projection.py --verify
// model: UnstableLlama/Qwen3.5-2B-exl3-8.00bpw/model.safetensors
// model SHA-256: {MODEL_SHA256}
// fixture: zig/tests/fixtures/exl3_oracle.bin
// fixture SHA-256: {FIXTURE_SHA256}
// source: public mcg 8.00-bpw oracle block, tiles K=8,N=8 (128x128).
// kPayloadSha256 covers the emitted u8 input, u8 weights, CPU integer dots,
// and three IEEE-754 scales; it is the content address of this QNN fixture.
constexpr char kFixtureSha256[] = "{FIXTURE_SHA256}";
constexpr char kPayloadSha256[] = "{digest}";
constexpr uint32_t kInputColumns = 128;
constexpr uint32_t kOutputColumns = 128;
constexpr float kInputScale = {input_scale:.8e}f;
constexpr int32_t kInputOffset = -128;
constexpr float kWeightScale = {weight_scale:.8e}f;
constexpr int32_t kWeightOffset = -128;
constexpr float kOutputScale = {output_scale:.8e}f;
constexpr int32_t kOutputOffset = {output_offset};
// One output-code LSB plus float accumulation allowance, in real units.
constexpr float kParityTolerance = kOutputScale * 1.5f;

constexpr uint8_t kInput[kInputColumns] = {{
{format_array(input_u8)}
}};
constexpr uint8_t kWeights[kInputColumns * kOutputColumns] = {{
{format_array(weights_u8)}
}};
constexpr int32_t kQuantizedDot[kOutputColumns] = {{
{format_array(dots, 8)}
}};
// Independent integer-domain CPU reference: dot * inputScale * weightScale.
constexpr float kQuantizedReference[kOutputColumns] = {{
{format_float_array(references)}
}};

}}  // namespace tensorfold::qnn_full_projection
'''


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--verify", action="store_true", help="fail unless the checked-in header exactly matches regeneration")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    data = FIXTURE.read_bytes()
    actual_fixture_hash = hashlib.sha256(data).hexdigest()
    if actual_fixture_hash != FIXTURE_SHA256:
        raise SystemExit(f"fixture SHA-256 mismatch: {actual_fixture_hash}")
    generated = render(data)
    if args.verify:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != generated:
            raise SystemExit("generated QNN full projection header is stale or altered")
        return 0
    args.output.write_text(generated, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
